#!/usr/bin/env python3
"""Summarise a posts.jsonl corpus (from tiktok_corpus.py) into a markdown stats page.

Usage:
  python3 tools/channel_stats.py data/raw/jason_swet/posts.jsonl > research/channel-stats.md

Format labels are keyword guesses from caption + transcript, not hand labels.
"""
import json
import re
import statistics
import sys

FORMATS = [  # first match wins
    ("sponsored", r"#\w*partner\b|#ad\b|\bpartnered\b|use my code|sponsored by|try musicbed|\bthanks @\w+ for (sending|the)"),
    ("technique", r"technique|semantic compounding|pattern break|form substitution|figure.?ground|gaze cue|"
                  r"frame within|visual literalism|hockney|taxonomy of visuals|visual lineage|visual tension|ingredients"),
    ("taste", r"\btaste\b"),
    ("tools", r"bookmark|toolbox|🧰|\btools?\b|website|resources|mockup"),
    ("teardown", r"campaign|art direction of|\bads?\b|commercial|launch film|music video|brand"),
    ("career", r"creative director|art director|career|bootcamp|portfolio|junior|school|mentor"),
]


def label(rec):
    # The caption states the post's intent; the transcript is only a fallback.
    for text in (rec.get("caption", ""), rec.get("transcript", "")):
        for name, pat in FORMATS:
            if re.search(pat, text.lower()):
                return name
    return "other"


def load(path):
    recs = {}
    for line in open(path):
        try:
            rec = json.loads(line)
        except json.JSONDecodeError:
            continue
        if "error" not in rec:
            recs[rec["id"]] = rec
    return list(recs.values())


def short(s, n=70):
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= n else s[: n - 1] + "…"


def main(path):
    recs = load(path)
    for r in recs:
        r["format"] = label(r)
        r["save_rate"] = r["saves"] / r["plays"] if r["plays"] else 0.0

    dates = sorted(r["created"] for r in recs)
    out = [
        "# @jason_swet: channel stats",
        "",
        f"{len(recs)} posts, {dates[0]} to {dates[-1]}. Generated by `tools/channel_stats.py` from the local corpus.",
        "Format labels are keyword guesses, not hand labels. Save rate = saves / plays.",
        "",
        "## By format",
        "",
        "| Format | Posts | Median plays | Median saves | Median save rate |",
        "|---|---:|---:|---:|---:|",
    ]
    for name in [f[0] for f in FORMATS] + ["other"]:
        group = [r for r in recs if r["format"] == name]
        if not group:
            continue
        out.append(
            f"| {name} | {len(group)} | {statistics.median(r['plays'] for r in group):,.0f} | "
            f"{statistics.median(r['saves'] for r in group):,.0f} | "
            f"{statistics.median(r['save_rate'] for r in group):.1%} |")

    def table(title, rows):
        out.extend(["", f"## {title}", "",
                    "| Date | Format | Plays | Saves | Save rate | Caption |",
                    "|---|---|---:|---:|---:|---|"])
        for r in rows:
            out.append(f"| {r['created']} | {r['format']} | {r['plays']:,} | {r['saves']:,} | "
                       f"{r['save_rate']:.1%} | [{short(r['caption'])}]({r['url']}) |")

    table("Top 15 by saves", sorted(recs, key=lambda r: -r["saves"])[:15])
    table("Top 15 by save rate (min 10K plays)",
          sorted([r for r in recs if r["plays"] >= 10_000], key=lambda r: -r["save_rate"])[:15])
    table("Top 10 by plays", sorted(recs, key=lambda r: -r["plays"])[:10])
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
